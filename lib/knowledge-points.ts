/**
 * 规范化知识点缓存键：去掉"（待补充）"标记、去首尾空白、压缩连续空格。
 * 待补充标签会回落到其基础标签，复用基础标签的讲义缓存。
 */
export function normalizeKnowledgePointKey(kp: string): string {
  return kp
    .replace(/[（(]待补充[）)]/g, "")
    .trim()
    .replace(/\s+/g, " ")
    .slice(0, 200);
}
